package ru.solomentsev.core.protocol;

/**
 * Поставщик инструментов отдельного продукта Atlassian.
 *
 * <p>Каждый продукт регистрирует собственные инструменты независимо от
 * остальных продуктов. Для подключения нового продукта достаточно добавить
 * реализацию этого интерфейса и передать её в точке сборки приложения.</p>
 */
public interface ToolProvider {

    /**
     * Регистрирует инструменты продукта в MCP-протоколе.
     *
     * @param protocol MCP-протокол, в который добавляются инструменты
     */
    void register(McpProtocol protocol);
}
